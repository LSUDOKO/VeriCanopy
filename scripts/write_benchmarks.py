"""Render docs/BENCHMARKS.md from measured artifacts only (never hand-typed numbers)."""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "ai" / "zk" / "artifacts"


def load(name: str) -> dict | None:
    p = ART / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def v(d: dict | None, k: str, unit: str = "", nd: int = 3) -> str:
    if not d or k not in d or d[k] is None:
        return "—"
    x = d[k]
    if isinstance(x, float):
        x = f"{x:,.{nd}f}".rstrip("0").rstrip(".")
    elif isinstance(x, int):
        x = f"{x:,}"
    return f"{x}{unit}"


def gas_rows() -> list[str]:
    p = ROOT / "docs" / "gas-report.txt"
    if not p.exists():
        return ["| — | — | — | — |"]
    rows = []
    for line in p.read_text().splitlines():
        m = re.match(r"\| (\w+)\s+\| (\d+)\s+\| (\d+)\s+\| (\d+)\s+\| (\d+)\s+\| (\d+)\s+\|", line)
        if m and m.group(1) in {"submitScore", "finalize", "addCells", "createProject", "openChallenge", "vote", "mintVintage", "retire", "handleReversal", "proveOverlap", "withdraw", "registerKey", "verifyProof"}:
            rows.append(f"| `{m.group(1)}` | {int(m.group(2)):,} | {int(m.group(4)):,} | {int(m.group(5)):,} |")
    return rows or ["| — | — | — | — |"]


