"use client";

import { useQuery } from "@tanstack/react-query";
import { useMemo, useState } from "react";
import { Bar, BarChart, Cell, ReferenceLine, ResponsiveContainer, Tooltip, XAxis, YAxis } from "recharts";
import { api, type Project, type Submission } from "@/lib/api";
import { fetchExplain, MCP_TOOLS, MCP_URL } from "@/lib/ask";
import { PageHero } from "@/components/PageHero";
import { HashChip } from "@/components/HashChip";
import { AuditorReport } from "@/components/AuditorReport";
import { ErrorState, Skeleton } from "@/components/States";

const MCP_CONFIG = (url: string) =>
  JSON.stringify({ mcpServers: { vericanopy: { type: "http", url } } }, null, 2);

function Copy({ text }: { text: string }) {
  const [ok, setOk] = useState(false);
  return (
    <button
      className="btn btn-ghost text-xs"
      onClick={() => {
        navigator.clipboard?.writeText(text);
        setOk(true);
        setTimeout(() => setOk(false), 1200);
      }}
    >
      {ok ? "Copied" : "Copy"}
    </button>
  );
}

export default function AskPage() {
  const projects = useQuery({ queryKey: ["projects"], queryFn: () => api<{ projects: Project[] }>("/projects") });
  const list = useMemo(() => (projects.data?.projects ?? []).filter((p) => p.integrity.latest_submission), [projects.data]);
  const [pidSel, setPid] = useState<number | null>(null);
  const pid = pidSel ?? list[0]?.id ?? null;
  const hist = useQuery({ queryKey: ["history", pid], queryFn: () => api<{ submissions: Submission[] }>(`/projects/${pid}/history`), enabled: pid !== null });
  const periods = useMemo(() => Array.from(new Set((hist.data?.submissions ?? []).map((s) => s.period))).sort((a, b) => b - a), [hist.data]);
  const [periodSel, setPeriod] = useState<number | null>(null);
  const period = periodSel !== null && periods.includes(periodSel) ? periodSel : (periods[0] ?? null);
  const ex = useQuery({ queryKey: ["explain", pid, period], queryFn: () => fetchExplain(pid!, period!), enabled: pid !== null && period !== null });
  const d = ex.data;
  const chart = (d?.drivers ?? []).slice(0, 10).map((r) => ({ name: r.label.length > 34 ? r.label.slice(0, 32) + "…" : r.label, c: +(r.contribution * 100).toFixed(2), full: r.sentence }));

  return (
    <div className="flex flex-1 flex-col">
      <PageHero title="Ask VeriCanopy" lede="Why did a forest get the score it got? Every answer below is computed from the signed manifest and the published model, not generated by a language model." />
      <div className="mx-auto w-full max-w-6xl px-4 pb-16 flex flex-col gap-6">
        <div className="card p-4 flex flex-wrap items-end gap-3">
          <label className="flex-1 min-w-56">
            <span className="label">Project</span>
            <select className="input" value={pid ?? ""} onChange={(e) => setPid(Number(e.target.value))}>
              {list.map((p) => (
                <option key={p.id} value={p.id}>
                  #{p.id} · {p.name ?? "Project"} ({p.country ?? "—"})
                </option>
              ))}
            </select>
          </label>
          <label className="w-40">
            <span className="label">Period</span>
            <select className="input" value={period ?? ""} onChange={(e) => setPeriod(Number(e.target.value))}>
              {periods.map((y) => (
                <option key={y} value={y}>
                  {y}
                </option>
              ))}
            </select>
          </label>
        </div>

        {ex.isLoading && <Skeleton className="h-48" />}
        {ex.error && <ErrorState error={ex.error} onRetry={() => ex.refetch()} />}
        {d && !d.available && <div className="card p-6 text-sm">{d.reason}</div>}
        {d?.available && (
          <>
            <section className="grid gap-4 lg:grid-cols-[1fr_1.4fr]">
              <div className="card p-6 flex flex-col gap-4">
                <div className="label">Integrity score · {d.period}</div>
                <div className="display text-6xl leading-none">{(d.score_bps / 100).toFixed(1)}<span className="text-2xl" style={{ color: "var(--fg-muted)" }}> / 100</span></div>
                <p className="text-sm leading-relaxed">{d.summary}</p>
                <div className="flex flex-wrap gap-2">
                  <span className="chip">{d.proof.verified_onchain ? "zk proof verified on-chain" : `proof: ${d.proof.mode ?? "none"}`}</span>
                  <span className="chip">{d.signature.algorithm ?? "unsigned"}</span>
                  <span className="chip" style={d.model_hash_matches_artifact ? undefined : { ["--tag-bg" as string]: "#fde8e8", ["--tag-ink" as string]: "#8a1c1c" }}>
                    {d.model_hash_matches_artifact ? "model hash matches artifact" : "model hash differs from local artifact"}
                  </span>
                  <span className="chip">{d.proof.status}</span>
                </div>
                <div className="flex flex-wrap gap-2 text-xs">
                  <HashChip label="model" value={d.model_hash} />
                  <HashChip label="manifest" value={d.signature.manifest_cid} kind="cid" />
                  <HashChip label="submit tx" value={d.proof.tx_hash} kind="tx" />
                  {d.proof.finalized_tx && <HashChip label="finalize tx" value={d.proof.finalized_tx} kind="tx" />}
                </div>
              </div>
              <div className="card p-6">
                <div className="label mb-2">What moved the score (percentage points vs a typical parcel)</div>
                <div className="h-80 w-full">
                  <ResponsiveContainer>
                    <BarChart data={chart} layout="vertical" margin={{ left: 8, right: 16, top: 4, bottom: 4 }}>
                      <XAxis type="number" tick={{ fontSize: 11 }} unit=" pp" />
                      <YAxis type="category" dataKey="name" width={190} tick={{ fontSize: 11 }} />
                      <ReferenceLine x={0} stroke="var(--border)" />
                      <Tooltip formatter={(v) => [`${v} pp`, "contribution"]} labelFormatter={(_, p) => (p?.[0]?.payload as { full: string } | undefined)?.full ?? ""} contentStyle={{ background: "var(--surface)", borderColor: "var(--border)", fontSize: 12, maxWidth: 320, whiteSpace: "normal" }} />
                      <Bar dataKey="c" radius={6}>
                        {chart.map((e, i) => (
                          <Cell key={i} fill={e.c >= 0 ? "var(--teal)" : "var(--red)"} />
                        ))}
                      </Bar>
                    </BarChart>
                  </ResponsiveContainer>
                </div>
                <div className="text-xs mt-2" style={{ color: "var(--fg-muted)" }}>{d.method}</div>
              </div>
            </section>

            <section className="grid gap-4 md:grid-cols-2">
              <div className="card p-5">
                <div className="label mb-2">Supports the score</div>
                <ul className="flex flex-col gap-2 text-sm">
                  {d.positive_drivers.length === 0 && <li style={{ color: "var(--fg-muted)" }}>Nothing above baseline.</li>}
                  {d.positive_drivers.map((r) => (
                    <li key={r.feature} className="flex gap-2">
                      <span style={{ color: "var(--teal)" }}>▲</span>
                      <span>{r.sentence}</span>
                    </li>
                  ))}
                </ul>
              </div>
              <div className="card p-5">
                <div className="label mb-2">Holds it back</div>
                <ul className="flex flex-col gap-2 text-sm">
                  {d.negative_drivers.length === 0 && <li style={{ color: "var(--fg-muted)" }}>No material negative drivers.</li>}
                  {d.negative_drivers.map((r) => (
                    <li key={r.feature} className="flex gap-2">
                      <span style={{ color: "var(--red)" }}>▼</span>
                      <span>{r.sentence}</span>
                    </li>
                  ))}
                </ul>
              </div>
            </section>

            <section className="card p-5">
              <div className="flex flex-wrap items-baseline justify-between gap-2">
                <div className="label">Data behind the answer · {d.provenance ?? "unknown provenance"}</div>
                {d.date_ranges && (
                  <div className="text-xs mono" style={{ color: "var(--fg-muted)" }}>
                    {Object.entries(d.date_ranges).map(([k, v]) => `${k}: ${v[0]} → ${v[1]}`).join("   ")}
                  </div>
                )}
              </div>
              <div className="mt-3 grid gap-2 sm:grid-cols-2 lg:grid-cols-3 text-sm">
                {d.data_sources.map((s) => (
                  <div key={s.id ?? s.name} className="rounded-xl border p-3" style={{ borderColor: "var(--border)" }}>
                    <div className="font-medium">{s.name}</div>
                    <div className="text-xs" style={{ color: "var(--fg-muted)" }}>{s.role}</div>
                    <div className="mono text-[11px] mt-1 break-all" style={{ color: "var(--fg-muted)" }}>{s.id}</div>
                  </div>
                ))}
              </div>
            </section>

            {pid !== null && period !== null && <AuditorReport projectId={pid} period={period} />}
          </>
        )}

        <section className="card p-6 grid gap-6 lg:grid-cols-2">
          <div>
            <div className="label">Connect your agent</div>
            <h2 className="text-2xl font-semibold tracking-tight mt-1">VeriCanopy MCP server</h2>
            <p className="text-sm mt-2" style={{ color: "var(--fg-muted)" }}>
              Any Model Context Protocol client (Claude Desktop, Claude Code, Cursor) can read the registry, explain scores and prepare unsigned marketplace or retirement transactions for your wallet to sign. Read-only; it never holds keys.
            </p>
            <div className="mt-4 flex items-center justify-between gap-2">
              <span className="label">Claude Code</span>
              <Copy text={`claude mcp add --transport http vericanopy ${MCP_URL}`} />
            </div>
            <pre className="mono text-xs rounded-xl p-3 overflow-auto" style={{ background: "var(--surface-2)" }}>{`claude mcp add --transport http vericanopy ${MCP_URL}`}</pre>
            <div className="mt-3 flex items-center justify-between gap-2">
              <span className="label">Claude Desktop / Cursor config</span>
              <Copy text={MCP_CONFIG(MCP_URL)} />
            </div>
            <pre className="mono text-xs rounded-xl p-3 overflow-auto" style={{ background: "var(--surface-2)" }}>{MCP_CONFIG(MCP_URL)}</pre>
          </div>
          <div>
            <div className="label mb-2">Tools</div>
            <ul className="grid gap-1.5 text-sm">
              {MCP_TOOLS.map(([n, desc]) => (
                <li key={n} className="flex gap-3 rounded-lg px-2 py-1.5" style={{ background: "var(--surface-2)" }}>
                  <code className="mono text-xs shrink-0 pt-0.5">{n}</code>
                  <span style={{ color: "var(--fg-muted)" }}>{desc}</span>
                </li>
              ))}
            </ul>
          </div>
        </section>
      </div>
    </div>
  );
}
